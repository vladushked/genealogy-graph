/**
 * The plugin's words in English and Russian. English is the base; every Russian entry mirrors it, so a missing
 * translation is a type error. The language is the plugin setting, or Obsidian's own language for «auto».
 */

export type Lang = 'en' | 'ru';
export type LanguageSetting = 'auto' | Lang;

import type { NamePart, NameScheme } from './names';

let current: Lang = 'en';
export const language = (): Lang => current;
export function setLanguage(lang: Lang) { current = lang; }
/** The language for a setting: «auto» follows Obsidian (`getLanguage()`), Russian for `ru`, otherwise English. */
export const resolveLanguage = (setting: LanguageSetting, obsidian: string): Lang =>
  setting === 'auto' ? (obsidian.toLowerCase().startsWith('ru') ? 'ru' : 'en') : setting;

/** Russian plural: 1 человек, 2 человека, 5 человек. */
export function ruPlural(n: number, one: string, few: string, many: string): string {
  const tens = Math.abs(n) % 100; const units = Math.abs(n) % 10;
  return tens >= 11 && tens <= 14 ? many : units === 1 ? one : units >= 2 && units <= 4 ? few : many;
}
const enPlural = (n: number, one: string, many: string) => n === 1 ? one : many;

